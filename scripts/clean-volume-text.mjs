/**
 * clean-volume-text.mjs — scrub literal markdown artifacts from plain-text
 * fields of all 50 volume data modules (+ volumesData.json mirror).
 *
 * Rationale: story panels, table cells, key facts, FAQs etc. render as PLAIN
 * text (or inline-markdown in the new <InlineMd/>), but the data still carried
 * `**bold**` markers, `### ` heading hashes, `•⁃▪` bullet glyphs and leftover
 * `[text]` brackets from the source manuscripts. This script strips those
 * artifacts while PRESERVING:
 *   - real markdown links  [label](https://…)   (now rendered as <a> tags)
 *   - blockquote '>' lines and content of `analysis` (true markdown documents)
 *   - en/em dashes and typographic hyphens (legit content, not artifacts)
 *
 * Run: node scripts/clean-volume-text.mjs
 */

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const REPO = path.resolve(__dirname, "..");
const VOL_DIR = path.join(REPO, "src/data/volumes");

// Fields that are rendered as markdown (or not rendered): do not touch.
const SKIP_KEYS = new Set(["analysis", "imagePrompt"]);

const clean = (s) => {
  if (typeof s !== "string") return s;
  let out = s;
  // **bold** / __bold__ -> plain text (renderer re-applies <strong> where wanted)
  out = out.replace(/\*\*([^*\n]{1,300}?)\*\*/g, "$1");
  out = out.replace(/__([^_\n]{1,300}?)__/g, "$1");
  out = out.replace(/\*\*/g, "");          // stray unpaired markers
  // *single-emphasis* on short spans only (avoids math asterisks)
  out = out.replace(/(^|[\s(>])\*([^*\n\\]{1,120}?)\*([\s).,:;!?]|$)/g, "$1$2$3");
  // `code` backticks
  out = out.replace(/`([^`\n]{1,120}?)`/g, "$1");
  // heading hashes at value/line start (parsed strings hold REAL newlines)
  out = out.replace(/(^|\n)[ \t]*#{1,6}[ \t]+/g, "$1");
  // unicode bullets at start of value/line -> clean prose
  out = out.replace(/(^|\n)[ \t]*[•⁃▪][ \t]+/g, "$1");
  // dash bullets ("- item") at line start only when followed by a letter
  out = out.replace(/(\n)[ \t]*[-–][ \t]+(?=[A-Za-z])/g, "$1");
  // mid-text " • " separators -> middle dot
  out = out.replace(/\s+•\s+/g, " · ");
  // leftover [text] with no following (url) -> text
  out = out.replace(/\[([^\]\n]{1,120})\](?!\()/g, "$1");
  // collapse triple spaces left behind
  out = out.replace(/[ \t]{2,}/g, " ").trimStart();
  return out;
};

let stats = { files: 0, stringsChanged: 0, bytesDelta: 0 };

const walk = (node) => {
  let changed = 0;
  if (Array.isArray(node)) {
    for (let i = 0; i < node.length; i++) {
      const v = node[i];
      if (typeof v === "string") {
        // String entries in arrays are plain-text fields (table rows, keyFacts…)
        const c = clean(v);
        if (c !== v) { node[i] = c; changed++; }
      } else {
        changed += walk(v);
      }
    }
  } else if (node && typeof node === "object") {
    for (const k of Object.keys(node)) {
      if (SKIP_KEYS.has(k)) continue;
      const v = node[k];
      if (typeof v === "string") {
        const c = clean(v);
        if (c !== v) { node[k] = c; changed++; }
      } else {
        changed += walk(v);
      }
    }
  }
  return changed;
};

// ---- 1) volume_XX.ts files -------------------------------------------------
// Shape: `export const volume_NN: Volume = { …JSON… };\n\nexport default volume_NN;`
for (const f of fs.readdirSync(VOL_DIR).sort()) {
  if (!/^volume_\d+\.ts$/.test(f)) continue;
  const p = path.join(VOL_DIR, f);
  const src = fs.readFileSync(p, "utf8");
  const m = src.match(/^export const (volume_\d+): Volume = \{/m);
  const endMark = src.lastIndexOf("\n};");
  if (!m || endMark === -1) { console.warn(`skip (unexpected shape): ${f}`); continue; }
  const braceIdx = m.index + m[0].length - 1; // the "{" that opens the object
  const body = src.slice(braceIdx, endMark + 2); // full "{...}" inclusive of both braces
  const tail = src.slice(endMark + 2); // ";" + "\n\nexport default volume_NN;\n"
  let obj;
  try {
    obj = JSON.parse(body); // data files are JSON-shaped (generated by assemble_volumes.py)
  } catch {
    console.warn(`skip (not JSON-parseable, manual review): ${f}`);
    continue;
  }
  const before = JSON.stringify(obj).length;
  const changed = walk(obj);
  if (changed > 0) {
    const after = JSON.stringify(obj).length;
    const out = src.slice(0, braceIdx) + JSON.stringify(obj, null, 2) + tail;
    fs.writeFileSync(p, out, "utf8");
    stats.files++;
    stats.stringsChanged += changed;
    stats.bytesDelta += after - before;
  }
}

// ---- 2) volumesData.json mirror --------------------------------------------
const mirrorPath = path.join(VOL_DIR, "volumesData.json");
if (fs.existsSync(mirrorPath)) {
  const data = JSON.parse(fs.readFileSync(mirrorPath, "utf8"));
  const changed = walk(Array.isArray(data) ? { items: data } : data);
  fs.writeFileSync(mirrorPath, JSON.stringify(Array.isArray(data) ? data : data, null, 2), "utf8");
  console.log(`volumesData.json: ${changed} strings scrubbed`);
}

console.log(`\nclean-volume-text: ${stats.files} volume files rewritten, ${stats.stringsChanged} strings scrubbed (${stats.bytesDelta} bytes).`);
